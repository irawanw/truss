"""Engine.generate (a mixin of server.engine.Engine): prompt reuse, greedy / sampled / speculative decode, stops.
"""
import threading
import time
import numpy as np
from server.chat import Detokenizer
from server.truss_ctypes import PENALTY_CAP, Sampling, TrussError
from server.words import WORD_FILLER, WORD_FILLER_WINDOW, WORD_REPEAT
from server.reasoning import BAN_EOS_IN_THINK, BAN_MAX_TOKENS
from server import vision_ds41

# The loop guard (TRUSS_LOOP_GUARD=0: off). A quantized model can fall into a verbatim loop: 10-21 the DS41 agent
# repeated one ~250-token paragraph of its reasoning until max_tokens. Every LOOP_EVERY generated tokens the tail is
# checked for back-to-back copies of one block of >= LOOP_MIN_PERIOD tokens: LOOP_COPIES inside the reasoning (the
# guard then feeds </think>: the model answers or acts with what it has), LOOP_COPIES_ANSWER in the answer (code and
# tables repeat legitimately more often; the guard then ends the reply).
import os
LOOP_GUARD = os.environ.get("TRUSS_LOOP_GUARD", "1") != "0"
LOOP_EVERY, LOOP_MIN_PERIOD, LOOP_MAX_PERIOD, LOOP_COPIES, LOOP_COPIES_ANSWER = 64, 64, 1024, 3, 5
CK_BACK = 4   # the prompt-end checkpoint sits this many tokens before the last turn marker
LOOP_LONG_PERIOD = 200   # in the reasoning, 2 copies of a block this long count too
# near-loops (no exact copy: "Let me run. Hmm." / "OK let me run now. Hmm." ...): the share of distinct 6-token
# phrases in the last 512 reasoning tokens. Calibrated 10-21 on the agent's own reasoning blocks: near-loops 0.30 and
# 0.36, exact loops 0.63-0.66 at their minimum, normal reasoning 0.99-1.0.
LOOP_VARIETY, LOOP_VARIETY_WINDOW, LOOP_VARIETY_N = 0.45, 512, 6


def variety(ids, w=LOOP_VARIETY_WINDOW, n=LOOP_VARIETY_N):
    """distinct n-grams / n-grams over the last w ids (1.0 when shorter)"""
    if len(ids) < w:
        return 1.0
    t = ids[-w:]
    return len({tuple(t[i:i + n]) for i in range(w - n + 1)}) / (w - n + 1)


def loop_period(ids, min_p=LOOP_MIN_PERIOD, max_p=LOOP_MAX_PERIOD, copies=LOOP_COPIES):
    """The shortest period p in [min_p, max_p] whose `copies` back-to-back copies end `ids`, or 0."""
    a = np.asarray(ids[-max_p * copies:], dtype=np.int64)
    n = len(a)
    for p in range(min_p, n // copies + 1):
        t = a[n - p * copies:]
        if np.array_equal(t[p:], t[:-p]):
            return p
    return 0


class _OneImage:
    """Flash-Next's one image as vision_ds41.reusable sees a span: row0, n, key() = ImageIn.span"""

    def __init__(self, image):
        self.row0, self.n, self._key = image.row0, image.nh * image.nw, image.span

    def key(self):
        return self._key


class EngineGenerate:
    """Engine.generate: one request's prompt read and decode loop on its slot (a mixin of server.engine.Engine)."""

    def generate(self, prompt_ids, max_tokens, temperature, top_p, top_k, seed, stop_strings, min_p=0.0,
                 presence_penalty=0.0, frequency_penalty=0.0, repetition_penalty=1.0, penalty_last_n=64,
                 think_open=False, note="", ignore_eos=False, image=None, spans=None):
        """Yields (token id, text delta, finish reason or None); the last item has the finish reason.
        Penalties (sampled requests only; greedy ignores them): llama.cpp's formulas over the last penalty_last_n
        tokens of the sequence (prompt included, as llama-server and Strata count), or with penalty_last_n -1 over
        every token generated by this request (vLLM's rule, which Qwen's presence_penalty advice assumes).
        image: Flash-Next's one image (read from position 0: the image prefix, the checkpoint, then text). spans: DS41's images (server/vision_ds41.py
        Span); the spans not yet in the slot go in with the rest of the read (one eval_imgs call per read), and
        reuse / restore stop at a cached span that is not this prompt's image.
        think_open: the prompt ends inside an open reasoning block (thinking on). Sampled requests then may not end
        the turn before </think>: the end-of-turn tokens are banned until </think> is fed. Without the ban a model
        that writes an end-of-turn marker literally in its reasoning (e.g. while discussing chat templates) emits the
        real token, the reply stops mid-sentence with no tool call, and an agent client stalls."""
        n_prompt = len(prompt_ids)
        if n_prompt == 0:
            raise ValueError("empty prompt")
        # One sequence for the whole request: a free slot (the one holding the longest prefix of this prompt), or a
        # FIFO wait while every slot is busy. `note` is the route's request line, logged here now that the slot, and
        # so the answer to "which stream said this", is known.
        slot = self.acquire_slot(prompt_ids, note)
        try:
            max_tokens = max(0, min(max_tokens, self.model.n_ctx - n_prompt))
            spans = spans or []
            # the prompt's images as a slot records them (row0, n, digest): DS41's spans, or Flash-Next's one image
            want = spans + ([_OneImage(image)] if image is not None else [])

            def fits(n, held):
                """A sequence holding the images `held` can serve this prompt's first n tokens: every held image that
                starts before n is the prompt's own at that row (equal ids cannot tell two pictures of one size
                apart; vision_ds41.reusable), and Flash-Next's image lies wholly inside them: it is read only from
                position 0 (the engine places its 3-D rope rows there), so a prompt whose image lies past the reused
                part reads everything again."""
                return (vision_ds41.reusable(n, held, want) >= n and
                        (image is None or image.row0 + image.nh * image.nw <= n))

            c = len(slot.cached)
            reuse = c if 0 < c < n_prompt and prompt_ids[:c] == slot.cached and fits(c, slot.images) else 0
            ck = len(slot.ck_tokens)
            if ck and not fits(ck, slot.ck_images):
                ck = 0
            back = (self.call(slot, self.model.restore)
                    if not reuse and 0 < ck < n_prompt and prompt_ids[:ck] == slot.ck_tokens else None)
            if back is not None and back != ck:
                self.log(f"{self.log_tag}: slot {slot.idx} checkpoint restore gave {back}, expected {ck}: full read")
            if back is not None and back == ck:
                # the last prompt is a prefix but its reply is not (the client re-sent it without its reasoning, or
                # edited it): back to the end of that prompt instead of reading everything again
                slot.cached, reuse = list(slot.ck_tokens), ck
                slot.images = list(slot.ck_images)
            if not reuse:
                self.call(slot, self.model.reset)   # an unrelated prompt: this slot's sequence starts over
                slot.cached, slot.ck_tokens = [], []   # reset drops the engine's checkpoint too
                slot.images, slot.ck_images = [], []
            elif image is not None:
                image = None   # the sequence already holds it (fits): the rest of the prompt is text
            greedy = temperature <= 0
            # sampled requests sample on the device and speculate too (Strata's sampled verify)
            sp = None if greedy else Sampling(temperature, top_p if top_p and top_p > 0 else 1.0, top_k or 0, min_p or 0.0,
                                              (seed if seed is not None else np.random.SeedSequence().entropy) % (1 << 64),
                                              repetition_penalty, frequency_penalty, presence_penalty,
                                              PENALTY_CAP if penalty_last_n < 0 else penalty_last_n)
            if (sp is not None and think_open and BAN_EOS_IN_THINK and self.think_close is not None
                    and self.think_close >= 0):
                sp.set_ban(sorted(self.stop_ids), self.think_close)
            if (sp is not None and think_open and WORD_REPEAT > 0 and getattr(self, "word_classes_set", False)
                    and self.think_close is not None and self.think_close >= 0):
                sp.set_word_repeat(WORD_REPEAT, self.think_close)   # server/words.py: no "maybe maybe" in the reasoning
                sp.set_filler(WORD_FILLER, WORD_FILLER_WINDOW)   # and no "Hmm ... Hmm ... Hmm" (needs the history)

            def counted():   # the tokens the penalties see, from the engine's own sequence
                if penalty_last_n < 0:
                    return slot.cached[n_prompt:]
                return slot.cached[-max(1, min(penalty_last_n, PENALTY_CAP)):]

            img_read = [image is not None]   # the prompt call is the only one that carries the image

            def step(tokens, ins=()):
                """Feed tokens on this slot, return the next token. The prompt's first read is the only call long
                enough to be split: while another slot has a request it goes in as pieces of plain eval and only the
                last piece is the step that samples, so the other stream gets its rounds in between. The head runs on
                the last row of every call, so where the pieces fall cannot change the result. ins: the DS41 image
                spans inside these tokens (one call carries them all)."""
                slot.cached += list(tokens)
                if ins:
                    imgs = span_args(ins, len(slot.cached) - len(tokens))
                    if sp is not None and sp.penalized:
                        sp.set_history(counted())
                    nxt = (self.call(slot, self.model.eval_imgs_argmax, tokens, imgs) if greedy
                           else self.call(slot, self.model.eval_imgs_sample, tokens, imgs, sp))
                    slot.images += [x.key() for x in ins]
                    return nxt
                if img_read[0]:
                    img_read[0] = False
                    if len(tokens) != n_prompt:
                        raise ValueError("an image prompt must be read in one call")
                    if sp is not None and sp.penalized:
                        sp.set_history(counted())
                    return (self.call(slot, self.model.eval_img_argmax, tokens, image.embeds, image.row0, image.nh,
                                      image.nw) if greedy
                            else self.call(slot, self.model.eval_img_sample, tokens, image.embeds, image.row0,
                                           image.nh, image.nw, sp))
                if self.prefill_piece > 0 and len(tokens) > self.prefill_piece and self.other_busy(slot):
                    self.read(slot, tokens[:-1])
                    tokens = tokens[-1:]
                if sp is not None and sp.penalized:
                    sp.set_history(counted())   # truss_eval_sample counts history as given: the fed tokens are in it
                return (self.call(slot, self.model.eval_argmax, tokens) if greedy
                        else self.call(slot, self.model.eval_sample, tokens, sp))

            def span_args(ins, start):   # (rows, row in this call) per span; the tower runs only for these
                return [(self.vision.span_rows(x.image, x.digest), x.row0 - start) for x in ins]

            def feed(lo, hi, step, last=False):
                """Prompt rows [lo, hi) as ONE call with every DS41 image span in them (a prompt call in stream mode
                pays a fixed expert-streaming cost, ~5 s per call on E2: one call per image made 16 compacted-history
                images cost 80 s). last: that call is the step that returns the next token; otherwise it only reads."""
                ins = [x for x in spans if lo <= x.row0 and x.row0 + x.n <= hi]
                if last:
                    return step(prompt_ids[lo:hi], ins)
                slot.cached += prompt_ids[lo:hi]
                if ins:
                    self.call(slot, self.model.eval_imgs, prompt_ids[lo:hi], span_args(ins, lo))
                    slot.images += [x.key() for x in ins]
                else:
                    self.read(slot, prompt_ids[lo:hi])
                return None

            t0 = time.time()
            n_read = n_prompt - reuse
            watch_stop, watcher = threading.Event(), None
            # truss_progress is per model, not per slot: watch it only when this read is one eval, because then
            # nothing else can hold the engine. A piece-wise read logs its own lines (Engine.read).
            if n_read > 4096 and not self.will_split(n_read, slot):
                self.progress(f"{self.log_tag}: slot {slot.idx} prefill start, {n_read} tokens to read "
                              f"({reuse} reused)")
                watcher = threading.Thread(target=self.watch_prefill, args=(n_read, 0, t0, watch_stop, slot.idx),
                                           daemon=True)
                watcher.start()
            try:
                # checkpoint just before the prompt's last <|im_start|> (DS41: <｜Assistant｜>, engine.py) (~10 ms): the
                # next request may resume there.
                # Not at the prompt's end: its generation prompt ("...assistant\n<think>\n") tokenizes differently
                # once the reply follows it ("\n\n</think>"). The text before the special token can change too:
                # a client that inserts a note there (oh-my-pi's loop guard, 10-22: "\n\n<system-interrupt ...>")
                # merges the last text token with it (">" + "\n\n" -> ">\n\n"), and 111 of 111 such turns read
                # the whole prompt again. So CK_BACK tokens earlier.
                cut = next((i for i in range(len(prompt_ids) - 1, reuse, -1) if prompt_ids[i] == self.im_start), 0)
                cut = vision_ds41.reusable(max(0, cut - CK_BACK), [], spans)   # not inside an image span
                if image is not None:   # (reuse 0) Flash-Next's image rows are read in the call from position 0
                    slot.images = [image.span]
                    if cut >= image.row0 + image.nh * image.nw:   # the image, then the checkpoint, then the tail
                        img_read[0] = False
                        slot.cached += prompt_ids[:cut]
                        self.call(slot, self.model.eval_img, prompt_ids[:cut], image.embeds, image.row0, image.nh,
                                  image.nw)
                        self.call(slot, self.model.checkpoint)
                        slot.ck_tokens, slot.ck_images = list(prompt_ids[:cut]), [image.span]
                        nxt = step(prompt_ids[cut:])
                    else:   # the image runs into the last turn: one call, no checkpoint
                        nxt = step(prompt_ids)
                else:
                    if cut > reuse:
                        feed(reuse, cut, step)
                        self.call(slot, self.model.checkpoint)
                        slot.ck_tokens = list(prompt_ids[:cut])
                        slot.ck_images = [r for r in slot.images if r[0] + r[1] <= cut]
                        reuse_from = cut
                    else:
                        reuse_from = reuse
                    nxt = feed(reuse_from, n_prompt, step, last=True)
            except TrussError:
                slot.cached, slot.ck_tokens = [], []   # the engine's sequence is unknown now: the next request starts over
                slot.images, slot.ck_images = [], []
                raise
            finally:
                watch_stop.set()
            t1 = time.time()
            if watcher:
                self.progress(f"{self.log_tag}: slot {slot.idx} prefill done, {n_read} tokens in {t1 - t0:.1f} s "
                              f"({n_read / max(t1 - t0, 1e-9):.0f} tok/s)")
            last_log, last_n = t1, 0
            detok, text, n_gen, finish = Detokenizer(self.chat), "", 0, "length"
            spec = self.model.drafts > 0
            drafted = accepted = n_rounds = 0
            pending = []   # tokens the engine already holds that are still to be emitted (speculative rounds)
            rounds = []    # (generated tokens before the round, emitted [nxt + accepted drafts], next): stop diagnosis
            t_round, max_gap = t1, 0.0   # the gap between the end of one round and the end of the next
            out_ids, in_think, guard_at, closed = [], think_open, LOOP_EVERY, False   # the loop guard's state
            think_from = 0   # where the reasoning started in out_ids (the variety window stays inside it)
            close_id = getattr(self, "think_close", None)   # None in the host tests' bare engines
            try:
                while n_gen < max_tokens:
                    if LOOP_GUARD and not pending and n_gen >= guard_at:   # at a round boundary: nxt not fed yet
                        guard_at = n_gen + LOOP_EVERY
                        copies = LOOP_COPIES if in_think else LOOP_COPIES_ANSWER
                        p = loop_period(out_ids, copies=copies)
                        why = f"{copies} copies of a {p}-token block"
                        if not p and in_think:   # a long block repeated once is already a loop (10-21: 462 tokens x 3)
                            p = loop_period(out_ids, min_p=LOOP_LONG_PERIOD, copies=2)
                            why = f"2 copies of a {p}-token block"
                        if not p and in_think and len(out_ids) - think_from >= LOOP_VARIETY_WINDOW:
                            v = variety(out_ids)
                            if v < LOOP_VARIETY:   # a near-loop: report it as one, the reaction is the same
                                p, why = LOOP_VARIETY_WINDOW, f"a near-loop (distinct 6-grams {v:.2f} in the last 512)"
                        if p and in_think and not closed and close_id is not None and close_id >= 0:
                            self.log(f"{self.log_tag}: slot {slot.idx} LOOP GUARD at gen {n_gen}: {why} in the "
                                     f"reasoning; </think> fed")
                            nxt, closed = close_id, True
                        elif p:
                            self.log(f"{self.log_tag}: slot {slot.idx} LOOP GUARD at gen {n_gen}: {why}; reply ended")
                            finish = "stop"
                            break
                    if spec and not pending:   # one round: nxt plus the accepted drafts enter the sequence
                        if slot.pos + 1 >= self.model.n_ctx:
                            break
                        if not greedy and sp.penalized:
                            sp.set_history(counted())   # before nxt; the engine adds nxt and the drafts per row
                        elif not greedy and sp.filler > 0:
                            sp.set_history(slot.cached[-WORD_FILLER_WINDOW:])   # the filler window, before nxt
                        emitted, after = (self.call(slot, self.model.spec_step, nxt) if greedy
                                          else self.call(slot, self.model.spec_step_sampled, nxt, sp))
                        rounds.append((len(slot.cached) - n_prompt, list(emitted), after))   # stop diagnosis
                        slot.cached += emitted
                        drafted += self.model.drafts
                        accepted += len(emitted) - 1
                        pending, nxt = emitted, after
                        n_rounds += 1
                        tr = time.time()
                        max_gap = max(max_gap, tr - t_round)   # what the other stream's prefill costs this stream
                        t_round = tr
                    tok = pending.pop(0) if spec else nxt
                    n_gen += 1
                    out_ids.append(tok)
                    if tok == close_id:
                        in_think = False
                        if sp is not None and (sp.word_repeat > 0 or sp.filler > 0):
                            sp.set_word_repeat(0.0)   # the answer may repeat a word (the engine lifted it in-call)
                            sp.set_filler(0.0)
                    if sp is not None and sp.n_ban and (tok == self.think_close or n_gen >= BAN_MAX_TOKENS):
                        # the reasoning block closed (the engine lifts the ban only inside the call that feeds
                        # </think>), or it ran so long that a stuck reply must still be able to end
                        sp.set_ban([])
                    if tok in self.stop_ids and not ignore_eos:
                        finish = "stop"
                        self.log_stop(slot, tok, n_prompt, n_gen, rounds)
                        break
                    delta = detok.push(tok)
                    text += delta
                    hit = next((s for s in stop_strings if s and s in text), None)
                    if hit:
                        cut = text.index(hit)
                        yield tok, delta[:max(0, len(delta) - (len(text) - cut))], None
                        finish = "stop"
                        break
                    yield tok, delta, None
                    now = time.time()
                    if now - last_log >= 3.0:   # live decode rate in the console / pm2 log: whole reply, last ~3 s
                        rate_now = (n_gen - last_n) / max(now - last_log, 1e-9)
                        last_log, last_n = now, n_gen
                        self.progress(f"{self.log_tag}: slot {slot.idx} decode {n_gen} tokens, "
                                      f"{n_gen / max(now - t1, 1e-9):.1f} tok/s (now {rate_now:.1f}), "
                                      f"drafts accepted {accepted} of {drafted}")
                    if not spec and n_gen < max_tokens and slot.pos < self.model.n_ctx:
                        nxt = step([nxt])
            except TrussError:
                slot.cached = []
                raise
            finally:
                t2 = time.time()
                read, gen_s = t1 - t0, t2 - t1
                self.last_rounds = n_rounds
                self.log(f"{self.log_tag}: prompt {n_prompt} tokens = {reuse} reused + {n_prompt - reuse} read in "
                         f"{read * 1e3:.0f} ms ({(n_prompt - reuse) / max(read, 1e-9):.1f} tok/s), {n_gen} generated "
                         f"in {gen_s * 1e3:.0f} ms ({n_gen / max(gen_s, 1e-9):.1f} tok/s), drafts accepted {accepted} of {drafted}, "
                         f"slot {slot.idx}, {n_rounds} rounds, longest gap between rounds {max_gap * 1e3:.0f} ms")
                self.save_request(prompt_ids, slot.cached[n_prompt:], finish, n_gen,
                                  dict(temperature=temperature, top_p=top_p, top_k=top_k, min_p=min_p, think_open=think_open))
                self.dump(prompt_ids, text, finish, dict(temperature=temperature, top_p=top_p, top_k=top_k, min_p=min_p,
                                                         presence_penalty=presence_penalty,
                                                         frequency_penalty=frequency_penalty,
                                                         repetition_penalty=repetition_penalty,
                                                         penalty_last_n=penalty_last_n))
            yield None, "", finish
        finally:
            self.release_slot(slot)   # a client disconnect closes the generator: the slot still comes back
